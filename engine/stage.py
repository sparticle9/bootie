#!/usr/bin/env python3
"""stage.py — materialize plan-driven bootie staging content (stdlib only).

Renders plan.env and the payload tree (write_files contents, runcmd scripts,
late_commands) into the initramfs staging directory. This logic is identical
in controller-driven and target-local modes — one implementation, no jinja.

Usage:
    stage.py --plan PLAN.json --key PUBKEY_FILE [--dest DIR]

Defaults to stdout for plan.env when --dest is omitted (debugging).
"""
import argparse
import base64
import json
import os
import sys


def q(value):
    """POSIX shell single-quote escaping — every plan.env value passes
    through this. The file is sourced by the liveenv shell: an embedded
    single quote or metacharacter must corrupt nothing, ever.
    Multi-line content (key files) is legal inside single quotes."""
    return "'" + str(value).replace("'", "'\\''") + "'"


def render_plan_env(plan, authkey, dns_default="8.8.8.8"):
    facts = plan["facts"]
    pers = plan.get("personalize", {})
    postinstall = plan.get("postinstall", {})
    cloud_ops = plan.get("cloud_ops", {})
    artifact = plan["artifact"]
    lines = [
        "# generated by bootie engine/stage.py — do not hand-edit on target",
        f"MANIFEST_NAME={q(plan['manifest']['name'])}",
        f"MANIFEST_VERSION={q(plan['manifest']['version'])}",
        f"MANIFEST_ARCH={q(plan['manifest']['arch'])}",
        f"PLAN_DISK={q(facts['disk_path'])}",
        f"FP_EXPECTED={q(plan['fingerprint'])}",
        f"FIRMWARE={q(facts['firmware'])}",
        f"ROOT_SUBVOL={q(pers.get('root_subvol', '@'))}",
        f"ROOTFS_TYPE={q(pers.get('rootfs') or 'btrfs')}",
        f"NET_BACKEND={q(pers.get('network') or 'networkmanager')}",
        f"BIOS_BOOT_METHOD={q(pers.get('bios_boot') or 'limine')}",
        f"FIRSTBOOT_CHECK_HOST={q(pers.get('connectivity_host') or 'archlinux.org')}",
        f"ART_URL={q(artifact['url'])}",
        f"ART_SHA256={q(artifact.get('sha256', ''))}",
        f"ART_CHECKSUM_ALG={q(artifact.get('checksum_alg', 'sha256'))}",
        f"ART_CHECKSUM={q(artifact.get('checksum') or artifact.get('sha256', ''))}",
        f"ART_UNPACKED={q(artifact.get('unpacked_url', ''))}",
        f"AUTHKEY={q(authkey)}",
        f"HOSTNAME_V={q(cloud_ops.get('hostname') or facts['hostname'])}",
        f"LOCALE_V={q(cloud_ops.get('locale') or 'en_US.UTF-8')}",
        f"TIMEZONE_V={q(cloud_ops.get('timezone') or '')}",
        f"NET_IF={q(facts['net_if'])}",
        f"IPV4_ADDR={q(facts['ipv4_addr'])}",
        f"IPV4_GW={q(facts['ipv4_gateway'])}",
        f"IPV6_ADDR={q(facts.get('ipv6_addr', ''))}",
        f"IPV6_GW={q(facts.get('ipv6_gateway', ''))}",
        f"DNS={q(facts.get('dns') or dns_default)}",
        f"BOOT_TARGET={q(postinstall.get('boot_target', 'desktop'))}",
        f"MANAGED_USER={q(postinstall.get('managed_user', ''))}",
        f"INSTALL_OM_DESKTOP={q('1' if postinstall.get('install_om_desktop') else '0')}",
    ]
    webapps = pers.get("remove_webapps") or []
    lines.append(f"REMOVE_WEBAPP_COUNT={len(webapps)}")
    for i, app in enumerate(webapps, 1):
        lines.append(f"REMOVE_WEBAPP_{i}_B64={q(base64.b64encode(app.encode()).decode())}")
    lines.append(f"DROP_PKGS={q(' '.join(pers.get('drop_pkgs') or []))}")
    users = cloud_ops.get("users") or []
    lines.append(f"USER_COUNT={len(users)}")
    for i, u in enumerate(users, 1):
        lines.append(f"USER_{i}_NAME={q(u['name'])}")
        lines.append(f"USER_{i}_GROUPS={q(','.join(u.get('groups') or []))}")
        lines.append(f"USER_{i}_SHELL={q(u.get('shell', ''))}")
        lines.append(f"USER_{i}_LOCK={1 if u.get('lock_passwd') else 0}")
        lines.append(f"USER_{i}_PASSWD_B64={q(base64.b64encode((u.get('passwd') or '').encode()).decode())}")
        lines.append(f"USER_{i}_SUDO_B64={q(base64.b64encode((u.get('sudo') or '').encode()).decode())}")
        keys = "\n".join(u.get("keys") or [])
        lines.append(f"USER_{i}_KEYS_B64={q(base64.b64encode(keys.encode()).decode())}")
    files = cloud_ops.get("files") or []
    lines.append(f"FILE_COUNT={len(files)}")
    for i, f in enumerate(files, 1):
        lines.append(f"FILE_{i}_PATH={q(f['path'])}")
        lines.append(f"FILE_{i}_OWNER={q(f['owner'])}")
        lines.append(f"FILE_{i}_PERMS={q(f['permissions'])}")
    lines.append(f"RUNCMD_COUNT={len(cloud_ops.get('runcmd') or [])}")
    lines.append(f"LATE_COUNT={len(pers.get('late_commands') or [])}")
    lines.append(f"CC_PACKAGES={q(' '.join(cloud_ops.get('packages') or []))}")
    lines.append(f"CC_PACKAGE_UPDATE={1 if cloud_ops.get('package_update') else 0}")
    return "\n".join(lines) + "\n"


def stage_payload(plan, dest):
    """Materialize payload/files/N, payload/runcmd/N.sh, payload/late/N.sh."""
    cloud_ops = plan.get("cloud_ops", {})
    pers = plan.get("personalize", {})
    for sub in ("files", "runcmd", "late"):
        os.makedirs(os.path.join(dest, "payload", sub), exist_ok=True)
    for i, f in enumerate(cloud_ops.get("files") or [], 1):
        out = os.path.join(dest, "payload", "files", str(i))
        with open(out, "wb") as fh:
            fh.write(base64.b64decode(f["content_b64"]))
        os.chmod(out, 0o600)
    for i, rc in enumerate(cloud_ops.get("runcmd") or [], 1):
        out = os.path.join(dest, "payload", "runcmd", f"{i}.sh")
        with open(out, "w") as fh:
            fh.write("#!/bin/sh\n" + rc + "\n")
        os.chmod(out, 0o700)
    for i, lc in enumerate(pers.get("late_commands") or [], 1):
        out = os.path.join(dest, "payload", "late", f"{i}.sh")
        with open(out, "w") as fh:
            fh.write("#!/bin/sh\n" + lc + "\n")
        os.chmod(out, 0o700)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True)
    ap.add_argument("--key", required=True, help="install public keys file (authorized_keys format, possibly several lines)")
    ap.add_argument("--dest", help="staging dir; stdout for plan.env when omitted")
    ap.add_argument("--dns", default="8.8.8.8")
    args = ap.parse_args()

    plan = json.load(open(args.plan))
    authkey = open(args.key).read().strip()
    env = render_plan_env(plan, authkey, args.dns)
    if not args.dest:
        sys.stdout.write(env)
        return 0
    os.makedirs(args.dest, exist_ok=True)
    with open(os.path.join(args.dest, "plan.env"), "w") as fh:
        fh.write(env)
    os.chmod(os.path.join(args.dest, "plan.env"), 0o600)
    stage_payload(plan, args.dest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
